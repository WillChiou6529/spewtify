    .padding(horizontal = 16.dp)
    .padding(top = 24.dp, bottom = 8.dp)

@Composable
fun ArtistOverview(
    youtubeArtistPage: Innertube.ArtistPage?,
    onViewAllSongsClick: () -> Unit,
    onViewAllAlbumsClick: () -> Unit,
    onViewAllSinglesClick: () -> Unit,
    onAlbumClick: (String) -> Unit,
    thumbnailContent: @Composable () -> Unit,
    headerContent: @Composable (textButton: (@Composable () -> Unit)?) -> Unit,
    modifier: Modifier = Modifier,
    // 線上資料還沒載入時先用資料庫裡的大頭照，版面才不會在載入完成時跳動
    placeholderHeroUrl: String? = null
) = LayoutWithAdaptiveThumbnail(
    thumbnailContent = thumbnailContent,
    modifier = modifier
) {
    val (colorPalette, typography) = LocalAppearance.current
    val binder = LocalPlayerServiceBinder.current
    val menuState = LocalMenuState.current
    val windowInsets = LocalPlayerAwareWindowInsets.current

    val endPaddingValues = windowInsets.only(WindowInsetsSides.End).asPaddingValues()

    val scrollState = rememberScrollState()

    Box {
        Column(
            horizontalAlignment = Alignment.CenterHorizontally,
            modifier = Modifier
                .background(colorPalette.background0)
                .fillMaxSize()
                .verticalScroll(scrollState)
                .padding(
                    windowInsets
                        .only(WindowInsetsSides.Vertical)
                        .asPaddingValues()
                )
        ) {
            // Spewtify：Spotify 藝人頁——滿版大頭照（下緣漸暗）→ 名字與操作 → 隨機＋綠色播放鍵
            val heroUrl = youtubeArtistPage?.thumbnail?.url ?: placeholderHeroUrl
            // 線上藝人載入中也先留 300dp 的位置（本機藝人沒有線上頁面，沒有照片時才用圓形縮圖）
            val showHero = !isLandscape && (heroUrl != null || youtubeArtistPage == null)
            if (showHero) Box(
                modifier = Modifier
                    .fillMaxWidth()
                    .height(300.dp)
                    .background(colorPalette.background1)
            ) {
                if (heroUrl != null) AsyncImage(
                    model = heroUrl.thumbnail(720),
                    contentDescription = null,
                    contentScale = ContentScale.Crop,
                    modifier = Modifier.matchParentSize()
                )
                Box(
                    modifier = Modifier
                        .matchParentSize()
                        .background(
                            Brush.verticalGradient(
                                0.5f to Color.Transparent,
                                1f to colorPalette.background0
                            )
                        )
                )
            }

            Box(modifier = Modifier.padding(endPaddingValues)) {
                headerContent {
                    youtubeArtistPage?.subscribersCountText?.let { subscribers ->
                        BasicText(
                            text = stringResource(R.string.format_subscribers, subscribers),
                            style = typography.xxs.medium
                        )
                    }
                }
            }

            // 沒有線上大頭照（本機藝人）才用原本的圓形縮圖
            if (!showHero && !isLandscape) thumbnailContent()

            SpotifyPlayRow(
                enabled = youtubeArtistPage != null,
                shuffleEnabled = youtubeArtistPage?.shuffleEndpoint != null,
                onShuffle = {
                    youtubeArtistPage?.shuffleEndpoint?.let { endpoint ->
                        binder?.stopRadio()
                        binder?.playRadio(endpoint)
                    }
                },
                onPlay = {
                    // 先播熱門歌曲，後面接藝人電台（像 Spotify 不會放完幾首就停）；沒有熱門歌曲就直接開電台
                    val top = youtubeArtistPage?.songs.orEmpty()
                    val radio = youtubeArtistPage?.radioEndpoint
                    binder?.stopRadio()
                    if (top.isNotEmpty()) {
                        binder?.player?.forcePlayFromBeginning(top.map { it.asMediaItem })
                        radio?.let { binder?.setupRadio(it) }
                    } else radio?.let { binder?.playRadio(it) }
                }
            )

            youtubeArtistPage?.let { artist ->
                artist.songs?.let { songs ->
                    Row(
                        verticalAlignment = Alignment.Bottom,
                        horizontalArrangement = Arrangement.SpaceBetween,
                        modifier = Modifier
                            .fillMaxSize()
                            .padding(endPaddingValues)
                    ) {
                        BasicText(
                            text = stringResource(R.string.songs),
                            style = typography.m.semiBold,
                            modifier = sectionTextModifier
                        )

                        artist.songsEndpoint?.let {
                            BasicText(
                                text = stringResource(R.string.view_all),
                                style = typography.xs.secondary,
                                modifier = sectionTextModifier.clickable(onClick = onViewAllSongsClick)
                            )
                        }
                    }

                    val [currentMediaId, playing] = playingSong(binder)

                    songs.forEach { song ->
                        SongItem(
                            song = song,
                            thumbnailSize = Dimensions.thumbnails.song,
                            modifier = Modifier
                                .combinedClickable(
                                    onLongClick = {
                                        menuState.display {
                                            NonQueuedMediaItemMenu(
                                                onDismiss = menuState::hide,
                                                mediaItem = song.asMediaItem
                                            )
                                        }
                                    },
                                    onClick = {
                                        val mediaItem = song.asMediaItem
                                        binder?.stopRadio()
                                        binder?.player?.forcePlay(mediaItem)
                                        binder?.setupRadio(
                                            NavigationEndpoint.Endpoint.Watch(videoId = mediaItem.mediaId)
                                        )
                                    }
                                )
                                .padding(endPaddingValues),
                            isPlaying = playing && currentMediaId == song.key
                        )
                    }
                }

                artist.albums?.let { albums ->
                    Row(
                        verticalAlignment = Alignment.Bottom,
                        horizontalArrangement = Arrangement.SpaceBetween,
                        modifier = Modifier
                            .fillMaxSize()
                            .padding(endPaddingValues)
                    ) {
                        BasicText(
                            text = stringResource(R.string.albums),
                            style = typography.m.semiBold,
                            modifier = sectionTextModifier
                        )

                        artist.albumsEndpoint?.let {
                            BasicText(
                                text = stringResource(R.string.view_all),
                                style = typography.xs.secondary,
                                modifier = sectionTextModifier.clickable(onClick = onViewAllAlbumsClick)
                            )
                        }
                    }

                    LazyRow(
                        contentPadding = endPaddingValues,
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        items(
                            items = albums,
                            key = Innertube.AlbumItem::key
                        ) { album ->
                            AlbumItem(
                                album = album,
                                thumbnailSize = Dimensions.thumbnails.album,
                                alternative = true,
                                modifier = Modifier.clickable {
                                    onAlbumClick(album.key)
                                }
                            )
                        }
                    }
                }

                artist.singles?.let { singles ->
                    Row(
                        verticalAlignment = Alignment.Bottom,
                        horizontalArrangement = Arrangement.SpaceBetween,
                        modifier = Modifier
                            .fillMaxSize()
                            .padding(endPaddingValues)
                    ) {
                        BasicText(
                            text = stringResource(R.string.singles),
                            style = typography.m.semiBold,
                            modifier = sectionTextModifier
                        )

                        artist.singlesEndpoint?.let {
                            BasicText(
                                text = stringResource(R.string.view_all),
                                style = typography.xs.secondary,
                                modifier = sectionTextModifier.clickable(onClick = onViewAllSinglesClick)
                            )
                        }
                    }

                    LazyRow(
                        contentPadding = endPaddingValues,
                        modifier = Modifier.fillMaxWidth()
                    ) {
                        items(
                            items = singles,
                            key = Innertube.AlbumItem::key
                        ) { album ->
                            AlbumItem(
                                album = album,
                                thumbnailSize = Dimensions.thumbnails.album,
                                alternative = true,
                                modifier = Modifier.clickable(onClick = { onAlbumClick(album.key) })
                            )
                        }
                    }
                }

                artist.description?.let { description ->
                    Attribution(
                        text = description,
                        modifier = Modifier
                            .padding(top = 16.dp)
                            .padding(vertical = 16.dp, horizontal = 8.dp)
                    )
                }

                Unit
            } ?: ArtistOverviewBodyPlaceholder()
        }

        // Spotify 沒有浮動按鈕：電台改由綠色播放鍵（沒有熱門歌曲時）開，這裡只保留回到頂端
        FloatingActionsContainerWithScrollToTop(scrollState = scrollState)
    }
}

@Composable
fun ArtistOverviewBodyPlaceholder(modifier: Modifier = Modifier) = ShimmerHost(
    modifier = modifier
) {
    TextPlaceholder(modifier = sectionTextModifier)

    repeat(5) {
        SongItemPlaceholder(thumbnailSize = Dimensions.thumbnails.song)
    }

    repeat(2) {
        TextPlaceholder(modifier = sectionTextModifier)

        Row {
            repeat(2) {
                AlbumItemPlaceholder(
                    thumbnailSize = Dimensions.thumbnails.album,
                    alternative = true
                )
            }
        }
    }
}
